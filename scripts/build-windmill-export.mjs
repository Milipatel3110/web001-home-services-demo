#!/usr/bin/env node
// Single source of truth for Windmill flow f/web001/contact_intake.
// Writes:
//   windmill/f/web001/contact_intake.flow/flow.yaml   (wmill sync layout, script referenced via !inline)
//   windmill/export/contact_intake.flow.json          (paste/import in the Windmill UI, script embedded)
// `--check` exits non-zero if either file is out of date (used by tests/CI).
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const flowDir = join(root, "windmill/f/web001/contact_intake.flow");
const scriptFile = "store_submission.inline_script.ts";
const yamlPath = join(flowDir, "flow.yaml");
const exportPath = join(root, "windmill/export/contact_intake.flow.json");

const field = (description, maxLength, extra = {}) => ({ type: "string", description, maxLength, ...extra });

function definition(content) {
  return {
    summary: "WEB-001 contact intake",
    description:
      "Called synchronously by Supabase Edge Function contact-submit. Idempotently stores a contact submission and returns {stored:true, request_id}.",
    value: {
      modules: [
        {
          id: "store_submission",
          summary: "Idempotent insert into public.contact_submissions",
          value: {
            type: "rawscript",
            language: "bun",
            content,
            input_transforms: {
              request_id: { type: "javascript", expr: "flow_input.request_id" },
              name: { type: "javascript", expr: "flow_input.name" },
              email: { type: "javascript", expr: "flow_input.email" },
              message: { type: "javascript", expr: "flow_input.message" },
              supabase_url: { type: "static", value: "$var:f/web001/supabase_url" },
              supabase_service_key: { type: "static", value: "$var:f/web001/supabase_service_key" },
            },
          },
          // Safe because the insert is idempotent on request_id.
          retry: { constant: { attempts: 2, seconds: 2 } },
        },
      ],
    },
    schema: {
      $schema: "https://json-schema.org/draft/2020-12/schema",
      type: "object",
      order: ["request_id", "name", "email", "message"],
      properties: {
        request_id: field("Client-generated UUID, idempotency key", 36),
        name: field("Sender name", 80, { minLength: 2 }),
        email: field("Sender email", 254, { format: "email" }),
        message: field("Message body", 1000, { minLength: 10 }),
      },
      required: ["request_id", "name", "email", "message"],
    },
  };
}

// Minimal YAML emitter: block mappings/sequences, JSON-quoted scalars (valid YAML).
function toYaml(value, indent = "") {
  if (Array.isArray(value)) {
    return value
      .map((item) => {
        const body = toYaml(item, indent + "  ");
        return typeof item === "object" && item !== null
          ? `${indent}- ${body.slice(indent.length + 2)}`
          : `${indent}- ${body.trim()}`;
      })
      .join("\n");
  }
  if (typeof value === "object" && value !== null) {
    return Object.entries(value)
      .map(([k, v]) => {
        const key = /^[A-Za-z_][A-Za-z0-9_]*$/.test(k) ? k : JSON.stringify(k);
        if (typeof v === "object" && v !== null && Object.keys(v).length > 0) {
          return `${indent}${key}:\n${toYaml(v, indent + "  ")}`;
        }
        return `${indent}${key}: ${typeof v === "object" ? (Array.isArray(v) ? "[]" : "{}") : JSON.stringify(v)}`;
      })
      .join("\n");
  }
  return indent + JSON.stringify(value);
}

const script = readFileSync(join(flowDir, scriptFile), "utf8");
const header = "# Generated by scripts/build-windmill-export.mjs - edit that file, then re-run it.\n";
const yaml = header + toYaml(definition(`!inline ${scriptFile}`)) + "\n";
const exported = JSON.stringify(definition(script), null, 2) + "\n";

if (process.argv.includes("--check")) {
  const stale = [];
  for (const [path, expected] of [[yamlPath, yaml], [exportPath, exported]]) {
    let actual = "";
    try { actual = readFileSync(path, "utf8"); } catch {}
    if (actual !== expected) stale.push(path);
  }
  if (stale.length) {
    console.error(`Out of date (run node scripts/build-windmill-export.mjs):\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log("Windmill flow export is up to date.");
} else {
  mkdirSync(dirname(exportPath), { recursive: true });
  writeFileSync(yamlPath, yaml);
  writeFileSync(exportPath, exported);
  console.log(`Wrote ${yamlPath}\nWrote ${exportPath}`);
}
